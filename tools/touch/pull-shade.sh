#!/system/bin/sh
# Вытягивание шторки «как пальцем»: касание у верха, пауза (у живого пальца между касанием и сдвигом 30–50 мс),
# затем плавно вниз и отпустить. su -c sh pull-shade.sh [пауза_мс]
D=/dev/input/event3
PAUSE=${1:-40}
e() { sendevent $D "$@"; }
e 3 47 0; e 3 57 201; e 3 53 300; e 3 54 20; e 3 48 6; e 1 330 1; e 0 0 0
sleep $(echo "$PAUSE" | awk '{printf "%.3f", $1/1000}')
y=20
while [ $y -lt 1400 ]; do y=$((y + 40)); e 3 54 $y; e 0 0 0; sleep 0.008; done
e 3 57 -1; e 1 330 0; e 0 0 0
