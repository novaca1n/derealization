#!/system/bin/sh
# Свайп двумя пальцами вниз через сенсор (fts_ts, протокол B, координаты = пиксели экрана).
# su -c sh two-finger-down.sh [x1 x2 y0 y1]. Начинать на ПУСТОМ месте стола — иначе касание достанется виджету.
D=/dev/input/event3
X1=${1:-350}; X2=${2:-730}; Y0=${3:-250}; Y1=${4:-600}
e() { sendevent $D "$@"; }
syn() { e 0 0 0; }
# два пальца вниз
e 3 47 0; e 3 57 101; e 3 53 $X1; e 3 54 $Y0; e 3 48 6
e 3 47 1; e 3 57 102; e 3 53 $X2; e 3 54 $Y0; e 3 48 6
e 1 330 1; syn
y=$Y0
while [ $y -lt $Y1 ]; do
    y=$((y + 25))
    e 3 47 0; e 3 54 $y; e 3 47 1; e 3 54 $y; syn
    sleep 0.012
done
# отпустить
e 3 47 0; e 3 57 -1; e 3 47 1; e 3 57 -1; e 1 330 0; syn
